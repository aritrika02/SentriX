import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {ZodError} from 'zod';
import authRoutes from './routes/auth.js';
import riskRoutes from './routes/risks.js';
import aiRoutes from './routes/ai.js';
import securityRoutes from './routes/security.js';
for(const key of ['MONGO_URI','JWT_SECRET','CLIENT_ORIGIN','ADMIN_SETUP_KEY'])if(!process.env[key])throw new Error(`Missing ${key} in .env`);
const app=express();app.disable('x-powered-by');app.use(helmet());app.use(cors({origin:process.env.CLIENT_ORIGIN.split(',').map(s=>s.trim())}));app.use(express.json({limit:'32kb'}));app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:80,standardHeaders:'draft-7',legacyHeaders:false}),authRoutes);app.use('/api/risks',riskRoutes);app.use('/api/ai',aiRoutes);app.use('/api/security',securityRoutes);app.get('/api/health',(_req,res)=>res.json({ok:true}));app.use((err,req,res,next)=>{if(err instanceof ZodError)return res.status(400).json({message:err.issues.map(i=>`${i.path.join('.')}: ${i.message}`).join('; ')});if(err.code===11000)return res.status(409).json({message:'Duplicate entry'});console.error(err);res.status(err.status||500).json({message:err.status?err.message:'Internal server error'});});
await mongoose.connect(process.env.MONGO_URI);app.listen(process.env.PORT||5000,()=>console.log(`SentriX API on port ${process.env.PORT||5000}`));
